from typing import TypedDict


# This typed dictionary stores the data passed between workflow steps.
class WorkflowState(TypedDict, total=False):
    """State container for the repository-analysis workflow.

    metadata_path: JSON file containing ingested repository chunks. output_path: Main output path for the architecture summary. summary: Architecture summary text generated by the workflow. reading_guide: Reading guide text for beginner onboarding. patch_file: Suggested patch file chosen for review. status: Current lifecycle state of the workflow.
    """

    metadata_path: str
    output_path: str
    summary: str
    reading_guide: str
    patch_file: str
    status: str
